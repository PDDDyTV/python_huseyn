a = input("Введи один символ: ")
if len(a) != 1:
    print("Нужно ввести только один символ")
elif a.isdigit():
    print("Это цифра.")
elif 'A' <= a <= 'Z' or 'А' <= a <= 'Я':
    print("Это БОЛЬШАЯ буква.")
elif 'a' <= a <= 'z' or 'а' <= a <= 'я':
    print("Это маленькая буква.")
elif a == " ":
    print("Это пробел.")
else:
    print("Это другой символ, например знак.")
